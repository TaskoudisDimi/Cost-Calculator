function get(obj: Record<string, any>, path: string): string {
  const result = path.split('.').reduce((o: any, k) => o?.[k], obj)
  return typeof result === 'string' ? result : path
}

export function useLocale() {
  function t(key: string): string {
    return get(messages[locale.value] as Record<string, any>, key)
  }

  function setLocale(l: Locale) {
    locale.value = l
    localStorage.setItem('app_locale', l)
  }

  return { t, locale: readonly(locale), setLocale }
}
